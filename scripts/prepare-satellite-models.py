"""Recenter and normalize verified glTF assets, preserving spacecraft geometry.
Usage: python scripts/prepare-satellite-models.py SOURCE_DIRECTORY
SOURCE_DIRECTORY holds the pinned NASA originals as iss.glb, hubble.glb and
terra.glb; Tiangong is generated by video/cinematic/tiangong_model.py.
NASA Terra references unavailable TGA files; retain material colors without those textures.
Hubble ships every texture twice (WebP and a PNG fallback of the same size);
keep only the WebP copies, which every supported browser decodes.
Meshes that arrive uncompressed (Terra, Tiangong) are Draco-compressed with
glTF Transform (npx, network needed once).
"""
import json,struct,sys,itertools,hashlib,subprocess,tempfile
from pathlib import Path
import numpy as np
sys.dont_write_bytecode=True
sys.path.insert(0,str(Path(__file__).resolve().parent.parent/'video'/'cinematic'))
import tiangong_model
GLTF_TRANSFORM='@gltf-transform/cli@4.1.1'
source=Path(sys.argv[1]);out=Path('public/models/satellites');out.mkdir(parents=True,exist_ok=True)

def read(path):
 raw=path.read_bytes();size=struct.unpack_from('<I',raw,12)[0]
 return raw,json.loads(raw[20:20+size]),raw[28+size:]

def write(path,doc,binary):
 encoded=json.dumps(doc,separators=(',',':')).encode();encoded+=b' '*((-len(encoded))%4)
 body=struct.pack('<I4s',len(encoded),b'JSON')+encoded+struct.pack('<I4s',len(binary),b'BIN\x00')+binary
 path.write_bytes(struct.pack('<4sII',b'glTF',2,12+len(body))+body)

def webp_only(doc,binary):
 """Point every texture at its EXT_texture_webp image and drop the PNG fallbacks."""
 fallbacks={t['source'] for t in doc['textures'] if 'EXT_texture_webp' in t.get('extensions',{})}
 for t in doc['textures']:
  if 'EXT_texture_webp' in t.get('extensions',{}):t.pop('source')
 keep=[i for i in range(len(doc['images'])) if i not in fallbacks];remap={old:new for new,old in enumerate(keep)}
 doc['images']=[doc['images'][i] for i in keep]
 for t in doc['textures']:
  ext=t.get('extensions',{}).get('EXT_texture_webp')
  if ext:ext['source']=remap[ext['source']]
 doc['extensionsRequired']=sorted(set(doc.get('extensionsRequired',[]))|{'EXT_texture_webp'})
 return compact(doc,binary)

def compact(doc,binary):
 """Rewrite the binary chunk with only the buffer views still referenced."""
 used=set()
 def collect(value,key=None):
  if isinstance(value,dict):
   for k,v in value.items():
    if k=='bufferView' and isinstance(v,int):used.add(v)
    else:collect(v,k)
  elif isinstance(value,list):
   for item in value:collect(item)
 for section in ['accessors','images','meshes']:collect(doc.get(section,[]))
 order=sorted(used);remap={old:new for new,old in enumerate(order)};data=bytearray();views=[]
 for old in order:
  view=dict(doc['bufferViews'][old]);start=view.get('byteOffset',0)
  data+=b'\0'*((-len(data))%4);view['byteOffset']=len(data);data+=binary[start:start+view['byteLength']];views.append(view)
 data+=b'\0'*((-len(data))%4)
 def renumber(value):
  if isinstance(value,dict):
   for k,v in value.items():
    if k=='bufferView' and isinstance(v,int):value[k]=remap[v]
    else:renumber(v)
  elif isinstance(value,list):
   for item in value:renumber(item)
 for section in ['accessors','images','meshes']:renumber(doc.get(section,[]))
 doc['bufferViews']=views;doc['buffers']=[{'byteLength':len(data)}]
 return doc,bytes(data)

records=[]
with tempfile.TemporaryDirectory() as scratch:
 tiangong_model.write_glb(Path(scratch)/'tiangong.glb')
 for name in ['iss','hubble','terra','tiangong']:
  raw,doc,binary=read((Path(scratch) if name=='tiangong' else source)/(name+'.glb'))
  nodes=doc['nodes'];roots=doc['scenes'][doc.get('scene',0)]['nodes'];points=[]
  def matrix(node):
   if 'matrix' in node:return np.array(node['matrix']).reshape((4,4),order='F')
   x,y,z,w=node.get('rotation',[0,0,0,1]);r=np.array([[1-2*(y*y+z*z),2*(x*y-z*w),2*(x*z+y*w)],[2*(x*y+z*w),1-2*(x*x+z*z),2*(y*z-x*w)],[2*(x*z-y*w),2*(y*z+x*w),1-2*(x*x+y*y)]])
   m=np.eye(4);m[:3,:3]=r@np.diag(node.get('scale',[1,1,1]));m[:3,3]=node.get('translation',[0,0,0]);return m
  def visit(i,parent):
   n=nodes[i];m=parent@matrix(n)
   if 'mesh' in n:
    for prim in doc['meshes'][n['mesh']]['primitives']:
     a=doc['accessors'][prim['attributes']['POSITION']]
     for xyz in itertools.product(*zip(a['min'],a['max'])):points.append((m@np.array([*xyz,1]))[:3])
   for c in n.get('children',[]):visit(c,m)
  for root in roots:visit(root,np.eye(4))
  lo=np.min(points,axis=0);hi=np.max(points,axis=0);span=float(max(hi-lo));center=(lo+hi)/2
  assert span>0 and np.isfinite(span)
  wrapper=np.eye(4);wrapper[:3,:3]/=span;wrapper[:3,3]=-center/span
  nodes.append({'name':'Earth Atlas normalized display frame','children':roots,'matrix':wrapper.flatten(order='F').tolist()});doc['scenes'][doc.get('scene',0)]['nodes']=[len(nodes)-1]
  if name=='terra':
   def clean(value):
    if isinstance(value,dict):
     for k in list(value):
      if k.endswith('Texture'):del value[k]
      else:clean(value[k])
    elif isinstance(value,list):
     for item in value:clean(item)
   clean(doc.get('materials',[]));doc.pop('images',None);doc.pop('textures',None);doc.pop('samplers',None)
   doc,binary=compact(doc,binary)
  if name=='hubble':doc,binary=webp_only(doc,binary)
  assert all('uri' not in b for b in doc.get('buffers',[]))
  assert all('uri' not in i for i in doc.get('images',[]))
  target=out/(name+'.glb');write(target,doc,binary)
  if 'KHR_draco_mesh_compression' not in doc.get('extensionsUsed',[]):
   subprocess.run(['npx','--yes',GLTF_TRANSFORM,'draco',str(target),str(target)],check=True,stdout=subprocess.DEVNULL)
  result=target.read_bytes()
  materials={'terra':'original colors; missing external textures removed','hubble':'original; WebP textures only (PNG duplicates removed)','tiangong':'schematic'}.get(name,'original')
  records.append({'id':name,'originalSha256':hashlib.sha256(raw).hexdigest(),'sha256':hashlib.sha256(result).hexdigest(),'bytes':len(result),'normalization':{'center':center.tolist(),'longestDimension':span},'materials':materials,'meshCompression':'draco'})
(out/'manifest.json').write_text(json.dumps(records,indent=2)+'\n')
print(json.dumps(records,indent=2))
